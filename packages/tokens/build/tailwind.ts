export interface ResolvedToken {
  value: string | number;
  type: string;
  cssVar: string;
  layer: "primitive" | "semantic" | "component";
  description?: string;
}

const dash = (name: string) => name.replaceAll(".", "-");

/**
 * Maps a design token to the Tailwind theme variable that exposes it, or `undefined` when the
 * token must stay out of Tailwind. Primitives are never exposed: utilities can only express
 * semantic intent (`bg-action-primary`), never a physical colour (`bg-blue-500`).
 */
function themeVariable(name: string, t: ResolvedToken): string | undefined {
  if (t.layer === "primitive" && !name.startsWith("font.")) return undefined;
  const [root, ...rest] = name.split(".");
  const key = rest.join("-");

  if (t.type === "color") return `--color-${t.layer === "semantic" ? key : dash(name)}`;

  switch (root) {
    case "radius":
      return `--radius-${key}`;
    case "spacing":
      return `--spacing-${key}`;
    case "size":
      return `--spacing-${key}`;
    case "elevation":
      return `--shadow-${key}`;
    case "font":
      return {
        family: `--font-${rest.slice(1).join("-")}`,
        size: `--text-${rest.slice(1).join("-")}`,
        weight: `--font-weight-${rest.slice(1).join("-")}`,
        "line-height": `--leading-${rest.slice(1).join("-")}`,
      }[rest[0] ?? ""];
    case "transition":
      return name === "transition.easing.default" ? `--ease-standard` : undefined;
    default:
      return undefined;
  }
}

/**
 * Renders the Tailwind v4 theme. `@theme inline` makes utilities emit `var(--ds-…)` directly
 * instead of going through a `--color-*` indirection declared on :root; that indirection would
 * be resolved once at the root and break nested `[data-theme]` subtrees.
 */
export function renderTailwindTheme(tokens: Record<string, ResolvedToken>): string {
  const lines: string[] = [];
  for (const [name, t] of Object.entries(tokens)) {
    const variable = themeVariable(name, t);
    if (variable) lines.push(`  ${variable}: var(${t.cssVar});`);
  }

  return `/**
 * Do not edit directly — generated by @design-system/tokens.
 * Tailwind consumes design tokens; it is never their source of truth.
 */
@theme inline {
  /* Drop Tailwind's default palette & scales: only design-system tokens may generate utilities. */
  --color-*: initial;
  --radius-*: initial;
  --shadow-*: initial;
  --spacing-*: initial;
  --text-*: initial;
  --font-*: initial;
  --leading-*: initial;
  --ease-*: initial;

  --spacing: var(--ds-spacing-1);
  --default-transition-duration: var(--ds-transition-duration-default);
  --default-transition-timing-function: var(--ds-transition-easing-default);

${lines.join("\n")}
}
`;
}
