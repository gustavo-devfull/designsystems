import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import StyleDictionary from "style-dictionary";
import type { File, TransformedToken } from "style-dictionary/types";
import { DIST, MOTION_TOKENS, PREFIX, THEMES, files, type Theme } from "./config.ts";

const PARTS = path.join(DIST, ".parts");

/**
 * `ds/name` — `ds-color-action-primary`. Drops DTCG `$root` segments so a group can be a token
 * itself (`color.action.primary`) and also own variants (`color.action.primary.hover`).
 */
StyleDictionary.registerTransform({
  name: "ds/name",
  type: "name",
  transform: (token) =>
    [PREFIX, ...token.path.filter((p) => p !== "$root")].join("-").toLowerCase(),
});

StyleDictionary.registerTransformGroup({
  name: "ds/css",
  transforms: [
    ...(StyleDictionary.hooks.transformGroups["css"] ?? []).filter((t) => t !== "name/kebab"),
    "ds/name",
  ],
});

interface Layer {
  id: string;
  source: string[];
  include: string[];
  /** CSS selector the variables are emitted under. */
  selector: string;
}

const primitiveAndShared = [...files.primitive, ...files.shared];

/**
 * Emission order matters for the cascade. Component tokens are re-declared on every
 * `[data-theme]` element: a `var()` in a custom property is resolved where it is declared,
 * so declaring them only on :root would freeze them to the root theme in nested themes.
 */
const layers: Layer[] = [
  { id: "base", source: primitiveAndShared, include: [], selector: ":root" },
  {
    id: "component",
    source: files.component,
    include: [...primitiveAndShared, ...files.mode("light")],
    selector: ":root, [data-theme]",
  },
  {
    id: "light",
    source: files.mode("light"),
    include: primitiveAndShared,
    selector: ':root, [data-theme="light"]',
  },
  {
    id: "dark",
    source: files.mode("dark"),
    include: primitiveAndShared,
    selector: '[data-theme="dark"]',
  },
];

const makeSd = (cfg: {
  source: string[];
  include?: string[];
  files?: File[];
  buildPath?: string;
}) =>
  new StyleDictionary({
    log: { verbosity: "silent", warnings: "disabled" },
    source: cfg.source,
    include: cfg.include ?? [],
    platforms: {
      css: {
        transformGroup: "ds/css",
        buildPath: cfg.buildPath ?? PARTS + "/",
        files: cfg.files ?? [],
      },
    },
  });

// ── 1. CSS ────────────────────────────────────────────────────────────────────────────────
rmSync(DIST, { recursive: true, force: true });
mkdirSync(PARTS, { recursive: true });

for (const layer of layers) {
  const sd = makeSd({
    source: layer.source,
    include: layer.include,
    files: [
      {
        destination: `${layer.id}.css`,
        format: "css/variables",
        // Include-only tokens (used to resolve references) are not emitted.
        filter: (token: TransformedToken) => token.isSource,
        options: { selector: layer.selector, outputReferences: true, showFileHeader: false },
      },
    ],
  });
  await sd.buildAllPlatforms();
}

const reducedMotion =
  `@media (prefers-reduced-motion: reduce) {\n  :root, [data-theme] {\n` +
  MOTION_TOKENS.map((t) => `    --${PREFIX}-${t.replaceAll(".", "-")}: 0.01ms;`).join("\n") +
  `\n  }\n}\n`;

const css =
  `/**\n * Do not edit directly — generated by @design-system/tokens (Style Dictionary).\n */\n\n` +
  layers.map((l) => readFileSync(path.join(PARTS, `${l.id}.css`), "utf8").trim()).join("\n\n") +
  `\n\n${reducedMotion}`;
writeFileSync(path.join(DIST, "tokens.css"), css);
rmSync(PARTS, { recursive: true, force: true });

// ── 2. JSON + TS (resolved, per theme) ────────────────────────────────────────────────────
interface ResolvedToken {
  value: string | number;
  type: string;
  cssVar: string;
  description?: string;
}

const dotted = (t: TransformedToken) => t.path.filter((p) => p !== "$root").join(".");

async function resolveTheme(theme: Theme): Promise<Record<string, ResolvedToken>> {
  const sd = makeSd({
    source: [...primitiveAndShared, ...files.mode(theme), ...files.component],
  });
  const { allTokens } = await sd.getPlatformTokens("css");
  const out: Record<string, ResolvedToken> = {};
  for (const t of allTokens) {
    out[dotted(t)] = {
      value: t.$value as string | number,
      type: t.$type ?? "",
      cssVar: `--${t.name}`,
      ...(typeof t.$description === "string" ? { description: t.$description } : {}),
    };
  }
  return Object.fromEntries(Object.entries(out).sort(([a], [b]) => a.localeCompare(b)));
}

const resolved = Object.fromEntries(
  await Promise.all(THEMES.map(async (t) => [t, await resolveTheme(t)] as const)),
) as Record<Theme, Record<string, ResolvedToken>>;

writeFileSync(
  path.join(DIST, "tokens.json"),
  JSON.stringify({ prefix: PREFIX, themes: THEMES, tokens: resolved }, null, 2) + "\n",
);

const values = Object.fromEntries(
  THEMES.map((t) => [
    t,
    Object.fromEntries(Object.entries(resolved[t]).map(([k, v]) => [k, v.value])),
  ]),
);
const vars = Object.fromEntries(Object.entries(resolved.light).map(([k, v]) => [k, v.cssVar]));

const ts = `/** Do not edit directly — generated by @design-system/tokens. */

export const cssVarPrefix = ${JSON.stringify(PREFIX)} as const;

export const themes = ${JSON.stringify(THEMES)} as const;
export type ThemeName = (typeof themes)[number];

/** Resolved values per theme (CSS-ready strings). */
export const tokenValues = ${JSON.stringify(values, null, 2)} as const;

export type TokenName = keyof (typeof tokenValues)["light"];

/** Token name → CSS custom property name. */
export const cssVars = ${JSON.stringify(vars, null, 2)} as const satisfies Record<TokenName, string>;

/** \`cssVar("color.action.primary")\` → \`var(--ds-color-action-primary)\` */
export function cssVar(name: TokenName): string {
  return \`var(\${cssVars[name]})\`;
}
`;
writeFileSync(path.join(DIST, "tokens.ts"), ts);

console.log(`✔ Built ${Object.keys(vars).length} tokens × ${THEMES.length} themes → dist/`);
